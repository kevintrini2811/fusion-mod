"""Generate plant identities, recognition, families and renderer entries. No game code runs."""
import argparse
import difflib
import json
from pathlib import Path
import re
import sys

PROJECT = Path(__file__).resolve().parents[1]
MANIFEST = "tools/plant-registrations.json"
PLANT = "src/FusionPlant.cs"
RENDERER = "src/ImportedPeaVisuals.cs"
START = "    // <generated-fusion-models>"
END = "    // </generated-fusion-models>"


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"Duplicate JSON key: {key}")
        result[key] = value
    return result


def validate(data):
    """Reject ambiguous identities, accidental registrations and invalid family graphs."""
    if not isinstance(data, dict) or set(data) != {"plants", "reserved", "families"}:
        raise ValueError("Expected plants, reserved and families")
    names, pairs, active = set(), set(), set()
    for section in ("plants", "reserved"):
        if not isinstance(data[section], list) or section == "plants" and not data[section]:
            raise ValueError(f"Expected nonempty plants and a reserved list: {section}")
        for row in data[section]:
            if not isinstance(row, dict) or set(row) != {"name", "native", "marker"}:
                raise ValueError(f"Expected name, native and marker in {section}")
            if any(not isinstance(value, str) or not re.fullmatch(r"[A-Z][A-Za-z0-9]*", value)
                   for value in row.values()):
                raise ValueError(f"Invalid C# identifier: {row}")
            name, native, marker = (row[key] for key in ("name", "native", "marker"))
            if name in names or name in {"FusionPlant", "From", "HasImportedVisuals", "NativeType", "Marker"}:
                raise ValueError(f"Duplicate or invalid plant name: {name}")
            if native in {"None", "Imitater"} or marker == "Imitater" or section == "reserved" and marker == "None":
                raise ValueError(f"Unsafe save identity: {name}")
            if (native, marker) in pairs:
                raise ValueError(f"Duplicate save identity: {native}, {marker}")
            names.add(name)
            pairs.add((native, marker))
            if section == "plants":
                active.add(name)
    families = data["families"]
    if not isinstance(families, dict):
        raise ValueError("Expected a family dictionary")
    for name, members in families.items():
        if not re.fullmatch(r"Is[A-Z][A-Za-z0-9]*", name) or name in names:
            raise ValueError(f"Invalid family name: {name}")
        if (not isinstance(members, list) or not members
                or any(not isinstance(member, str) for member in members)
                or len(set(members)) != len(members)):
            raise ValueError(f"Expected unique, nonempty family members: {name}")
        for member in members:
            if member not in active and member not in families:
                raise ValueError(f"Unknown or reserved family member: {name}.{member}")
    visited, visiting = set(), set()

    def visit(name):
        if name in visiting:
            raise ValueError(f"Cyclic family: {name}")
        if name in visited:
            return
        visiting.add(name)
        for member in families[name]:
            if member in families:
                visit(member)
        visiting.remove(name)
        visited.add(name)

    for name in families:
        visit(name)
    return data


def predicate(name, terms):
    # Keep generated comparisons readable without introducing runtime registries.
    lines = [f"    internal static bool {name}(FusionPlant plant) =>"]
    for index in range(0, len(terms), 3):
        tail = ";" if index + 3 >= len(terms) else " ||"
        lines.append("        " + " || ".join(terms[index:index + 3]) + tail)
    return "\n".join(lines)


def plant_source(data):
    lines = [
        "// Generated by tools/registrations.py from tools/plant-registrations.json.",
        "// Edit the manifest, not this file. Published save pairs must never change.",
        "using Il2CppReloaded.Gameplay;", "", "namespace FusionMod;", "",
        "// NativeType owns terrain and AI; Marker identifies the saved variant.",
        "// Source IDs must never be passed to native plant/controller APIs.",
        "internal readonly record struct FusionPlant(SeedType NativeType, SeedType Marker = SeedType.None)",
        "{",
    ]
    for row in data["plants"]:
        name, native, marker = (row[key] for key in ("name", "native", "marker"))
        if marker == "None":
            lines.append(f"    internal static FusionPlant {name} => SeedType.{native};")
        else:
            lines.append(f"    internal static readonly FusionPlant {name} = new(SeedType.{native}, SeedType.{marker});")
    if data["reserved"]:
        lines.extend(["", "    // Reserved synergies are not registered plants, recipes or renderers."])
        for row in data["reserved"]:
            lines.append(f"    internal static FusionPlant {row['name']} => new(SeedType.{row['native']}, SeedType.{row['marker']});")
    for name, members in data["families"].items():
        terms = [f"{member}(plant)" if member in data["families"] else f"plant == {member}"
                 for member in members]
        lines.extend(["", predicate(name, terms)])
    lines.extend(["", predicate("HasImportedVisuals", [f"plant == {row['name']}" for row in data["plants"]]),
                  "", "    internal static FusionPlant From(Plant plant) =>",
                  "        (plant.mSeedType, plant.mImitaterType) switch", "        {"])
    for row in data["plants"]:
        if row["marker"] != "None":
            lines.append(f"            (SeedType.{row['native']}, SeedType.{row['marker']}) => {row['name']},")
    # Registered plants from other mods keep their own recipe identity; native Imitaters stay native.
    lines.extend(["            _ => PlantLibrary.Plants.Find(plant) is { } registered",
                  "                ? new(registered.Identity.NativeType, registered.Identity.Marker) : new(plant.mSeedType)", "        };", "",
                  "    public static implicit operator FusionPlant(SeedType nativeType) => new(nativeType);",
                  "}", ""])
    return "\n".join(lines)


def renderer_source(data, original):
    if original.count(START) != 1 or original.count(END) != 1:
        raise ValueError("Expected exactly one generated renderer section")
    start, end = original.index(START), original.index(END)
    if end <= start:
        raise ValueError("Invalid generated renderer section")
    lines = [START, "    private static readonly Assets[] Models =", "    {"]
    for row in data["plants"]:
        lines.append(f"        new(FusionPlant.{row['name']}, \"{row['name']}\"),")
    lines.extend(["    };", END])
    newline = "\r\n" if "\r\n" in original else "\n"
    return original[:start] + newline.join(lines) + original[end + len(END):]


def generated_sources(project):
    data = validate(json.loads((project / MANIFEST).read_text(), object_pairs_hook=unique_object))
    renderer = (project / RENDERER).read_bytes().decode("utf-8")
    return {PLANT: plant_source(data).encode("utf-8"),
            RENDERER: renderer_source(data, renderer).encode("utf-8")}


def registration_errors(project):
    try:
        expected = generated_sources(project)
        return [f"Stale C# registrations: {name}; regenerate with tools/registrations.py"
                for name, content in expected.items() if (project / name).read_bytes() != content]
    except (ValueError, OSError) as error:
        return [f"Invalid C# registrations: {error}"]


def registration_patch(project):
    """Emit one reviewable patch; apply it with the same command as documentation patches."""
    paths = (MANIFEST, PLANT, RENDERER)
    originals = {name: (project / name).read_bytes() for name in paths}
    expected = generated_sources(project)
    chunks = []
    for name, content in expected.items():
        for line in difflib.unified_diff(originals[name].decode("utf-8").splitlines(keepends=True),
                                         content.decode("utf-8").splitlines(keepends=True),
                                         fromfile=f"a/{name}", tofile=f"b/{name}"):
            chunks.append(line if line.endswith("\n") else line + "\n\\ No newline at end of file\n")
    if any((project / name).read_bytes() != content for name, content in originals.items()):
        raise ValueError("Inputs changed during registration generation; regenerate the patch")
    return "".join(chunks)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail for stale generated C#; never write files")
    args = parser.parse_args()
    try:
        if args.check:
            errors = registration_errors(PROJECT)
            for error in errors:
                print("ERROR:", error)
            raise SystemExit(1 if errors else 0)
        sys.stdout.write(registration_patch(PROJECT))
    except (ValueError, OSError) as error:
        parser.exit(1, f"ERROR: {error}\n")
