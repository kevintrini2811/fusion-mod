    public static int Count => Recipes.Count;
    internal static IEnumerable<((FusionPlant Existing, FusionPlant Incoming) Ingredients, FusionPlant Result)> Entries =>
        Recipes.Select(entry => (entry.Key, entry.Value));

    // Enumerate the same unordered pairs used by planting and the glove.
    // A self-fusion contributes one partner; alternative results remain grouped.
    internal static IEnumerable<(FusionPlant Partner, FusionPlant Result)> Partners(FusionPlant ingredient)
    {
        foreach (var (pair, result) in Recipes)
        {
            if (pair.Existing == ingredient) yield return (pair.Incoming, result);
            else if (pair.Incoming == ingredient) yield return (pair.Existing, result);
        }
    }

    internal static bool IsPuffSpreading(FusionPlant existing, FusionPlant incoming) =>
        existing == (FusionPlant)SeedType.Puffshroom
        && (incoming == (FusionPlant)SeedType.Fumeshroom || incoming == (FusionPlant)SeedType.Scaredyshroom);

    public static bool TryGet(FusionPlant existing, FusionPlant incoming, out FusionPlant result) =>
        Recipes.TryGetValue((existing, incoming), out result)
        || !IsPuffSpreading(incoming, existing) && Recipes.TryGetValue((incoming, existing), out result);

    public static bool AcceptsIngredient(Plant plant, FusionPlant result)
    {
        if (result != SeedType.GiantWallnut) return true;
        // AnimateNuts switches to the first damaged graphic strictly below
        // floor(2 * maxHealth / 3). Minor bites above that boundary are allowed.
        return plant.mSeedType == SeedType.Wallnut && plant.mPlantMaxHealth > 0
            && plant.mPlantHealth >= (long)plant.mPlantMaxHealth * 2 / 3;
    }
